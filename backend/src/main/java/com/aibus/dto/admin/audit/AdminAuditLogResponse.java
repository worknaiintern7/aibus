package com.aibus.dto.admin.audit;

import java.time.LocalDateTime;

public class AdminAuditLogResponse {
    private Long id;
    private Long adminId;
    private String adminEmail;
    private String action;
    private String entityType;
    private String entityId;
    private String description;
    private LocalDateTime createdAt;

    public AdminAuditLogResponse() {
    }

    public AdminAuditLogResponse(Long id, Long adminId, String adminEmail, String action, String entityType, String entityId, String description, LocalDateTime createdAt) {
        this.id = id;
        this.adminId = adminId;
        this.adminEmail = adminEmail;
        this.action = action;
        this.entityType = entityType;
        this.entityId = entityId;
        this.description = description;
        this.createdAt = createdAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getAdminId() {
        return adminId;
    }

    public void setAdminId(Long adminId) {
        this.adminId = adminId;
    }

    public String getAdminEmail() {
        return adminEmail;
    }

    public void setAdminEmail(String adminEmail) {
        this.adminEmail = adminEmail;
    }

    public String getAction() {
        return action;
    }

    public void setAction(String action) {
        this.action = action;
    }

    public String getEntityType() {
        return entityType;
    }

    public void setEntityType(String entityType) {
        this.entityType = entityType;
    }

    public String getEntityId() {
        return entityId;
    }

    public void setEntityId(String entityId) {
        this.entityId = entityId;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
